def render_params(plan: ComponentPlan) -> list[str]:
    name = f"{plan.type_name}Params"
    fields, values, reads = [], [], []
    for param in plan.params:
        doc = param.description.replace("\n", " ") or None
        default = typed_literal(param.kind, param.default) if param.default is not None else None
        comment = " ".join(x for x in (doc, f"(default: {default})" if default else None) if x)
        if comment:
            fields.append(f"    /// {comment}")
        fields.append(f"    pub {param.ident}: Option<{RS_TYPES[param.kind]}>,")
        clone = "" if param.kind != "string" else ".clone()"
        values.append(f"            {rust_str(param.name)} => Value::from(self.{param.ident}{clone}),")
        convert = {"string": "v.text()", "int": "v.as_i64()", "float": "v.as_f64()", "bool": "v.as_bool()"}[
            param.kind
        ]
        reads.append(
            f"            {param.ident}: rt::arg(values, {rust_str(param.name)}).and_then(|v| {convert}),"
        )
    lines = [
        "",
        f"/// Parameters of the {rust_str(plan.component.name)} component.",
        "/// `None` keeps the parameter default, or else the value of the inner element.",
        "#[derive(Clone, Debug, Default)]",
        f"pub struct {name} {{",
        *fields,
        "}",
        "",
        f"impl rt::Params for {name} {{",
    ]
    if not plan.params:
        return [
            *lines,
            "    fn value(&self, _name: &str) -> Value {",
            "        Value::Null",
            "    }",
            "",
            "    fn from_values(_values: &[(String, Value)]) -> Self {",
            f"        {name} {{}}",
            "    }",
            "}",
        ]
    return [
        *lines,
        "    fn value(&self, name: &str) -> Value {",
        "        match name {",
        *values,
        "            _ => Value::Null,",
        "        }",
        "    }",
        "",
        "    fn from_values(values: &[(String, Value)]) -> Self {",
        f"        {name} {{",
        *reads,
        "        }",
        "    }",
        "}",
    ]


def _nested_field(scope: ScopePlan, element: str, param: str) -> str:
    instance = next(i for i in scope.instances.values() if i.node.name == element)
    return next((p.ident for p in instance.component.params if p.name == param), param)


def render_component(plan: ComponentPlan, renderer: ScopeRenderer) -> list[str]:
    scope = plan.scope
    instances = {i.node.name: i for i in scope.instances.values()}
    idents = {e.name: e.ident for e in scope.spec.elements}
    locals_, element_values, pad_values = [], [], []
    nested: dict[str, list[str]] = {}
    for param in plan.params:
        if not param.targets:
            continue
        default = typed_literal(param.kind, param.default) if param.default is not None else None
        locals_.append(
            f"let {param.ident} = params.{param.ident}.clone(){f'.or(Some({default}))' if default else ''};"
        )
        for target in param.targets:
            if target.element in instances:
                field = _nested_field(scope, target.element, target.property)
                nested.setdefault(target.element, []).append(
                    f"if {param.ident}.is_some() {{ "
                    f"args_{idents[target.element]}.{field} = {param.ident}.clone(); }}"
                )
                continue
            pad = f"Some({rust_str(target.pad)})" if target.pad else "None"
            statement = (
                f"rt::apply_value(&elements[{rust_str(target.element)}], {rust_str(target.property)}, "
                f"&Value::from({param.ident}.clone()), {pad})?;"
            )
            (pad_values if target.pad or target.pad_ref else element_values).append(statement)
    ports = ", ".join(f"{p.name} ({p.direction})" for p in plan.ports) or "none"
    params_arg = "params" if locals_ else "_params"
    host_arg = "host" if scope.probes or scope.instances else "_host"
    body = [
        "let container = gst::Bin::builder().name(name).build();",
        f"let {'mut ' if scope.spec.elements else ''}elements = Elements::new();",
        *locals_,
        *renderer.elements(scope, nested),
        *element_values,
        *renderer.links(scope),
        *pad_values,
        *[
            f"rt::expose_port(&container, &elements[{rust_str(p.element)}], {rust_str(p.pad)}, "
            f"{rust_str(p.name)}, {rust_str(p.presence)})?;"
            for p in plan.ports
        ],
        *renderer.probes(scope, plan.component.graph, True),
        "Ok(container)",
    ]
    signature = (
        f"pub fn build_{plan.ident}(name: &str, {params_arg}: &{plan.type_name}Params, "
        f"{host_arg}: &ProbeHost) "
        "-> Result<gst::Bin> {"
    )
    return [
        "",
        f"/// {plan.component.name}: a bin named `name` with ghost pads {ports}.",
        "/// Its probe rule sets start with `host` (the pipeline starts it on PLAYING).",
        signature,
        *[f"    {line}" for line in body],
        "}",
    ]


def render(
    graph: Graph, catalog: Catalog, name: str, components: Mapping[str, Component] | None = None
) -> str:
    program = build_program(graph, catalog, components or {}, name, RESERVED)
    slots = {s.slot.id: s.slot.id for s in program.slots} | {s.slot.name: s.slot.id for s in program.slots}
    functions = {f.function.name: f.ident for f in program.functions}
    types: dict[int, str] = {}
    rule_sets: list[str] = []
    for owner, scope in [(c.component.id, c.scope) for c in program.components] + [(name, program.root)]:
        for rule_set in scope.probes:
            types[id(rule_set)] = type_name(rule_set, owner)
            rule_sets += render_rule_set(rule_set, types[id(rule_set)], slots, functions)
    code = ["", "// ---- Probe rule sets", *rule_sets] if rule_sets else []
    if program.components:
        code += ["", "// ---- Components"]
    for component in program.components:
        code += render_params(component)
        code += render_component(component, ScopeRenderer(types, "host"))
    code += render_pipeline(program, graph, ScopeRenderer(types, "&host"))
    notes = comment_block(script_notes(graph, "rust"), "rust")
    if notes:
        code.append(notes.rstrip("\n"))
    support = VALUES + ELEMENTS + RULES + CORE_IMPL + RULE_SET + SLOTS
    return "\n".join([_prelude(program, code), support.strip("\n"), *code]) + "\n"


def _imports(code: list[str]) -> str:
    """``use rt::{…}`` with the names the generated code uses unqualified."""
    text = "\n".join(code)
    names = [
        n
        for n in ("Core", "Ctx", "Elements", "ProbeHost", "Value", "Vars", "Verdict")
        if re.search(rf"(?<!::)\b{n}\b", text)
    ]
    if "Params::from_values(" in text:
        names.append("Params")
    return f"use rt::{{{', '.join(sorted(names))}}};"


def _prelude(program: ProgramPlan, code: list[str]) -> str:
    api = [
        f"//!   pipeline.add_{s.item}(params)? / remove_{s.item}(id)? / list_{s.ident}()"
        for s in program.slots
    ]
    api += [f"//!   pipeline.{f.ident}(...)?" for f in program.functions]
    text = "\n".join(api)
    cls = f"{program.type_name}Pipeline"
    return _PRELUDE.format(
        name=program.name, cls=cls, api=text + "\n" if text else "", imports=_imports(code)
    )
