from pipelab.graph.models import Graph

_PY_TYPES = {"string": "str", "int": "int", "float": "float", "bool": "bool"}

_PRELUDE = '''#!/usr/bin/env python3
"""{name}: GStreamer pipeline generated by Pipelab.

Equivalent description (Gst.parse_launch / gst-launch-1.0):
    {description}

Use it from your application::

    pipeline = {cls}()
    pipeline.on_message(callback)   # every bus message
    pipeline.start()                # needs a running GLib main loop (see run())
    ...
    pipeline.send_eos()             # finish files cleanly, then stop()
{builders}
Run this file to try it.
"""

from __future__ import annotations

import signal
import sys

import gi

gi.require_version("Gst", "1.0")
from gi.repository import GLib, Gst  # noqa: E402

try:  # PyGObject >= 3.52 moved unix signal helpers to GLibUnix
    gi.require_version("GLibUnix", "2.0")
    from gi.repository import GLibUnix  # noqa: E402

    unix_signal_add = GLibUnix.signal_add
except (ImportError, ValueError):
    unix_signal_add = GLib.unix_signal_add
'''

_LIFECYCLE = '''
    def start(self) -> None:
        """Set the pipeline to PLAYING (a GLib main loop must run to dispatch the bus)."""
        if self.pipeline is None:
            self.build()
        bus = self.pipeline.get_bus()
        bus.add_signal_watch()
        bus.connect("message", self._on_bus)
        if self.pipeline.set_state(Gst.State.PLAYING) == Gst.StateChangeReturn.FAILURE:
            raise RuntimeError("the pipeline refused to start")

    def stop(self) -> None:
        if self.pipeline is not None:
            self.pipeline.set_state(Gst.State.NULL)
            self.pipeline.get_bus().remove_signal_watch()

    def send_eos(self) -> None:
        """Ask sources to finish so muxers and files are finalised cleanly."""
        if self.pipeline is not None:
            self.pipeline.send_event(Gst.Event.new_eos())

    def on_message(self, callback) -> None:
        """``callback(message)`` for every bus message, before the default handling."""
        self._callbacks.append(callback)

    def element(self, path: str) -> Gst.Element:
        """``name``, or ``instance/inner`` for elements inside components."""
        first, *rest = path.split("/")
        element = self.elements.get(first) or self.pipeline.get_by_name(first)
        for part in rest:
            element = element.get_by_name(part) if element is not None else None
        if element is None:
            raise KeyError(f"no element {path}")
        return element

    def _on_bus(self, _bus: Gst.Bus, message: Gst.Message) -> None:
        for callback in self._callbacks:
            callback(message)
        if message.type == Gst.MessageType.ERROR:
            error, debug = message.parse_error()
            print(f"ERROR from {message.src.get_path_string()}: {error.message}", file=sys.stderr)
            print(f"  {debug}", file=sys.stderr)
            self.exit_code = 1
            self._quit()
        elif message.type == Gst.MessageType.WARNING:
            warning, _debug = message.parse_warning()
            print(f"WARNING from {message.src.get_path_string()}: {warning.message}", file=sys.stderr)
        elif message.type == Gst.MessageType.EOS:
            self._quit()

    def _quit(self) -> None:
        if self.loop is not None:
            self.loop.quit()

    def run(self) -> int:
        """Play until end-of-stream or error; Ctrl+C sends EOS first."""
        self.loop = GLib.MainLoop()
        self.start()
        interrupt = lambda *_: self.send_eos() or GLib.SOURCE_CONTINUE  # noqa: E731
        unix_signal_add(GLib.PRIORITY_DEFAULT, signal.SIGINT, interrupt)
        try:
            self.loop.run()
        finally:
            self.stop()
        return self.exit_code


def main() -> int:
    Gst.init(sys.argv)
    return CLASS().run()


if __name__ == "__main__":
    sys.exit(main())
'''


def _typed_value(spec: PropertySpec) -> object:
    if spec.kind in ("float", "double"):
        return float(spec.value)  # type: ignore[arg-type]
    if spec.kind == "string":
        return str(spec.value)
    return spec.value


def _dicts(specs: tuple[PropertySpec, ...]) -> tuple[str, str]:
    """Typed values (set_property) and values parsed like gst-launch (enums, flags, caps…)."""
    typed = ", ".join(f"{p.name!r}: {_typed_value(p)!r}" for p in specs if p.kind != "parse")
    parsed = ", ".join(f"{p.name!r}: {p.text!r}" for p in specs if p.kind == "parse")
    return f"{{{typed}}}", f"{{{parsed}}}"


def _elements(scope: ScopePlan, nested: dict[str, list[str]] | None = None) -> list[str]:
    """Statements creating the elements (and component bins) of a scope into ``container``."""
    lines = []
    for element in scope.spec.elements:
        instance = scope.instances.get(element.node.id)
        if instance is None:
            typed, parsed = _dicts(element.properties)
            lines.append(
                f"elements[{element.name!r}] = make_element(container, {element.factory!r}, "
                f"{element.name!r}, {typed}, {parsed})"
            )
            continue
        params = instance.component.params
        values = {p.ident: instance.values[p.name] for p in params if p.name in instance.values}
        args = f"args_{element.ident}"
        lines.append(f"{args} = {values!r}")
        lines += (nested or {}).get(element.name, [])
        build = f"build_{instance.component.ident}({element.name!r}, **{args})"
        lines.append(f"elements[{element.name!r}] = {build}")
        lines.append(f"container.add(elements[{element.name!r}])")
    return lines


def _links(scope: ScopePlan) -> list[str]:
    """Links, then pad properties and pad-typed properties (they need the requested pads)."""
    lines = []
    for link in scope.spec.links:
        function = "link_dynamic" if link.edge.id in scope.dynamic_edges else "link"
        args = (link.source.name, link.source_pad, link.target.name, link.target_pad)
        lines.append(f"{function}(elements, {', '.join(repr(a) for a in args)})")
    for element in scope.spec.elements:
        if element.node.id in scope.instances:
            continue
        for pad, specs in element.pad_properties:
            typed, parsed = _dicts(specs)
            lines.append(f"configure(pad_of(elements[{element.name!r}], {pad!r})[0], {typed}, {parsed})")
        for ref in element.pad_refs:
            lines.append(f"apply_value(elements[{element.name!r}], {ref.name!r}, {str(ref.value)!r})")
    return lines


@dataclass
class _ParamLines:
    defaults: list[str] = field(default_factory=list)  # resolve definition defaults
    elements: list[str] = field(default_factory=list)  # inner element properties (before linking)
    pads: list[str] = field(default_factory=list)  # pad properties / pad references (after linking)
    nested: dict[str, list[str]] = field(default_factory=dict)  # kwargs of nested instances


def _param_lines(plan: ComponentPlan) -> _ParamLines:
    result = _ParamLines()
    instances = {i.node.name: i for i in plan.scope.instances.values()}
    idents = {e.name: e.ident for e in plan.scope.spec.elements}
    for param in plan.params:
        if param.default is not None:
            result.defaults.append(
                f"{param.ident} = {param.default!r} if {param.ident} is None else {param.ident}"
            )
        for target in param.targets:
            if target.element in instances:
                inner = instances[target.element].component.params
                key = next((p.ident for p in inner if p.name == target.property), target.property)
                result.nested.setdefault(target.element, []).extend(
                    [
                        f"if {param.ident} is not None:",
                        f"    args_{idents[target.element]}[{key!r}] = {param.ident}",
                    ]
                )
                continue
            element = f"elements[{target.element!r}]"
            statement = f"apply_value({element}, {target.property!r}, {param.ident}, {target.pad!r})"
            lines = [f"if {param.ident} is not None:", f"    {statement}"]
            (result.pads if target.pad or target.pad_ref else result.elements).extend(lines)
    return result


def _component(plan: ComponentPlan) -> list[str]:
    keywords = "".join(f", {p.ident}: {_PY_TYPES[p.kind]} | None = None" for p in plan.params)
    star = ", *" if plan.params else ""
    ports = ", ".join(f"{p.name} ({p.direction})" for p in plan.ports) or "none"
    params = _param_lines(plan)
    described = [f"{p.ident}: {_doc_text(p.description)}" for p in plan.params if p.description]
    body = [
        f'"""{_doc_text(plan.component.name)}: a bin with ghost pads {ports}.',
        *(["", *described] if described else []),
        '"""',
        "container = Gst.Bin.new(name)",
        "elements = {}",
        *params.defaults,
        *_elements(plan.scope, params.nested),
        *params.elements,
        *_links(plan.scope),
        *params.pads,
        *[
            f"expose_port(container, elements[{p.element!r}], {p.pad!r}, {p.name!r}, {p.presence!r})"
            for p in plan.ports
        ],
        "return container",
    ]
    signature = f"def build_{plan.ident}(name: str{star}{keywords}) -> Gst.Bin:"
    return ["", "", signature, *[f"    {line}".rstrip() for line in body]]


def _pipeline_class(program: ProgramPlan, cls: str) -> list[str]:
    build = [
        f"self.pipeline = Gst.Pipeline.new({program.name!r})",
        "container, elements = self.pipeline, self.elements",
        *_elements(program.root),
        *_links(program.root),
        "return self.pipeline",
    ]
    return [
        "",
        "",
        f"class {cls}:",
        f'    """{_doc_text(program.name)}: owns the pipeline, its elements and the bus handling."""',
        "",
        "    def __init__(self) -> None:",
        "        self.pipeline: Gst.Pipeline | None = None",
        "        self.elements: dict[str, Gst.Element] = {}",
        "        self._callbacks: list = []",
        "        self.loop: GLib.MainLoop | None = None",
        "        self.exit_code = 0",
        "",
        "    def build(self) -> Gst.Pipeline:",
        '        """Create the elements (and component bins), set their properties and link them."""',
        *[f"        {line}" for line in build],
        _LIFECYCLE.replace("CLASS", cls).rstrip("\n"),
    ]


def _doc_text(text: str) -> str:
    """Text safe inside a triple-quoted docstring."""
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def render(
    graph: Graph, catalog: Catalog, name: str, components: Mapping[str, Component] | None = None
) -> str:
    library = components or {}
    program = build_program(graph, catalog, library, name)
    stem = camel_case(name)
    cls = stem if stem.endswith("Pipeline") else f"{stem}Pipeline"
    builders = "".join(
        f"    build_{c.ident}(name, ...)  # {_doc_text(c.component.name)}: a Gst.Bin\n"
        for c in program.components
    )
    prelude = _PRELUDE.format(
        name=_doc_text(name),
        description=_doc_text(render_description(flatten(graph, library), catalog) or "(empty)"),
        cls=cls,
        builders=f"\nComponents (reusable bins)::\n\n{builders}" if builders else "",
    )
    lines = [prelude, SUPPORT.strip("\n")]
    for component in program.components:
        lines += _component(component)
    lines += _pipeline_class(program, cls)
    return "\n".join(lines) + "\n"
