_PRELUDE = """//! {name}: GStreamer pipeline generated by Pipelab.
//!
//! Cargo.toml dependencies:
//!   gstreamer = "0.25"
//!   anyhow = "1"
//!
//! Equivalent gst-launch-1.0 description:
//!   {description}

use anyhow::{{anyhow, Context, Result}};
use gstreamer as gst;
use gst::prelude::*;

/// Creates an element, sets its properties (parsed like gst-launch) and adds it.
fn make(
    pipeline: &gst::Pipeline,
    factory: &str,
    name: &str,
    properties: &[(&str, &str)],
) -> Result<gst::Element> {{
    let mut builder = gst::ElementFactory::make(factory).name(name);
    for (key, value) in properties {{
        builder = builder.property_from_str(key, value);
    }}
    let element = builder.build().with_context(|| format!("element '{{factory}}' is not installed"))?;
    pipeline.add(&element)?;
    Ok(element)
}}

fn link(src: &gst::Element, src_pad: &str, sink: &gst::Element, sink_pad: &str) -> Result<()> {{
    src.link_pads(Some(src_pad), sink, Some(sink_pad))
        .with_context(|| {{
            format!("could not link {{}}.{{src_pad}} to {{}}.{{sink_pad}}", src.name(), sink.name())
        }})
}}

/// Links a "sometimes" pad (matched by name or template) once it appears.
#[allow(dead_code)]
fn link_dynamic(src: &gst::Element, src_pad: &str, sink: &gst::Element, sink_pad: &str) -> Result<()> {{
    let target = sink
        .static_pad(sink_pad)
        .or_else(|| sink.request_pad_simple(sink_pad))
        .ok_or_else(|| anyhow!("{{}} has no pad {{sink_pad}}", sink.name()))?;
    let wanted = src_pad.to_string();
    src.connect_pad_added(move |element, pad| {{
        let matches = pad.name() == wanted.as_str()
            || pad.pad_template().is_some_and(|t| t.name_template() == wanted.as_str());
        if !matches || target.is_linked() || !pad.query_caps(None).can_intersect(&target.query_caps(None)) {{
            return;
        }}
        if let Err(err) = pad.link(&target) {{
            eprintln!("could not link {{}}.{{}}: {{err:?}}", element.name(), pad.name());
        }}
    }});
    Ok(())
}}

#[allow(dead_code)]
fn pad(element: &gst::Element, name: &str) -> Result<gst::Pad> {{
    element.static_pad(name).ok_or_else(|| anyhow!("{{}} has no pad {{name}}", element.name()))
}}

fn build_pipeline() -> Result<gst::Pipeline> {{
    let pipeline = gst::Pipeline::with_name({pipeline_name});
"""

_EPILOGUE = """
fn main() -> Result<()> {
    gst::init()?;
    let pipeline = build_pipeline()?;
    pipeline.set_state(gst::State::Playing)?;
    let bus = pipeline.bus().context("pipeline without bus")?;
    let mut result = Ok(());
    for message in bus.iter_timed(gst::ClockTime::NONE) {
        use gst::MessageView;
        match message.view() {
            MessageView::Eos(..) => break,
            MessageView::Error(err) => {
                let source = err.src().map(|s| s.path_string());
                result = Err(anyhow!("error from {source:?}: {} ({:?})", err.error(), err.debug()));
                break;
            }
            MessageView::Warning(warning) => {
                eprintln!("warning from {:?}: {}", warning.src().map(|s| s.path_string()), warning.error());
            }
            _ => (),
        }
    }
    pipeline.set_state(gst::State::Null)?;
    result
}
"""


def rust_string(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def _properties(specs: tuple[PropertySpec, ...]) -> str:
    pairs = ", ".join(f"({rust_string(p.name)}, {rust_string(p.text)})" for p in specs)
    return f"&[{pairs}]"


def _element_line(element: ElementSpec) -> str:
    identity = f"{rust_string(element.factory)}, {rust_string(element.name)}"
    args = f"&pipeline, {identity}, {_properties(element.properties)}"
    return f"    let {element.ident} = make({args})?;"


def _after_link_lines(element: ElementSpec) -> list[str]:
    lines = []
    for pad_name, specs in element.pad_properties:
        for spec in specs:
            lines.append(
                f"    pad(&{element.ident}, {rust_string(pad_name)})?"
                f".set_property_from_str({rust_string(spec.name)}, {rust_string(spec.text)});"
            )
    for ref in element.pad_refs:
        lines.append(
            f"    {element.ident}.set_property({rust_string(ref.name)}, "
            f"&pad(&{element.ident}, {rust_string(str(ref.value))})?);"
        )
    return lines


def _build_body(spec: PipelineSpec) -> list[str]:
    lines = [_element_line(element) for element in spec.elements]
    for link in spec.links:
        function = "link_dynamic" if link.dynamic else "link"
        lines.append(
            f"    {function}(&{link.source.ident}, {rust_string(link.source_pad)}, "
            f"&{link.target.ident}, {rust_string(link.target_pad)})?;"
        )
    for element in spec.elements:
        lines += _after_link_lines(element)
    return [*lines, "    Ok(pipeline)", "}"]


def render(graph: Graph, catalog: Catalog, name: str) -> str:
    spec = build_spec(graph, catalog, name, reserved=RUST_KEYWORDS)
    prelude = _PRELUDE.format(
        name=name,
        description=render_description(graph, catalog) or "(empty)",
        pipeline_name=rust_string(name),
    )
    notes = comment_block(script_notes(graph, "rust"), "rust")
    return prelude + "\n".join(_build_body(spec)) + "\n" + _EPILOGUE + notes
