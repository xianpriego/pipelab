"""gstreamer-rs library (``main.rs``): one builder per component and a type owning the pipeline."""

from __future__ import annotations

from collections.abc import Mapping

from pipelab.catalog.store import Catalog
from pipelab.components.models import Component
from pipelab.export.common import PropertySpec, camel_case
from pipelab.export.flatten import flatten
from pipelab.export.gst_launch import render_description
from pipelab.export.plan import ComponentPlan, ProgramPlan, ScopePlan, build_program
from pipelab.export.rust_support import PIPELINE, RT
from pipelab.export.rust_syntax import RUST_KEYWORDS, rust_str, typed_literal
from pipelab.graph.models import Graph

RS_TYPES: dict[str, str] = {"string": "String", "int": "i64", "float": "f64", "bool": "bool"}

_PRELUDE = """//! {name}: GStreamer pipeline generated by Pipelab.
//!
//! Cargo.toml dependencies:
//!   gstreamer = "0.25"
//!   anyhow = "1"
//!
//! Equivalent gst-launch-1.0 description:
//!   {description}
//!
//! Use it from your application (a GLib main loop must run, see `run()`):
//!   let pipeline = {cls}::new()?;
//!   pipeline.connect_message(|message| println!("{{:?}}", message.type_()));
//!   pipeline.start()?;
//!   // ... pipeline.send_eos(); then pipeline.stop()?;
{builders}
// The pipeline is a library: the demo `main` at the end uses only part of it.
#![allow(dead_code)]

use std::sync::{{Arc, Mutex}};

use anyhow::{{anyhow, Context, Result}};
use gst::glib;
use gst::prelude::*;
use gstreamer as gst;
use rt::Elements;
"""


def _property_list(specs: tuple[PropertySpec, ...]) -> str:
    return "&[" + ", ".join(f"({rust_str(p.name)}, {rust_str(p.text)})" for p in specs) + "]"


def _elements(scope: ScopePlan, nested: dict[str, list[str]] | None = None) -> list[str]:
    """Statements creating the elements (and component bins) of a scope into ``container``."""
    lines = []
    for element in scope.spec.elements:
        key = rust_str(element.name)
        instance = scope.instances.get(element.node.id)
        if instance is None:
            make = f"rt::make_element(&container, {rust_str(element.factory)}, {key}, "
            lines.append(f"elements.insert({key}.into(), {make}{_property_list(element.properties)})?);")
            continue
        component = instance.component
        fields = []
        for param in component.params:
            literal = typed_literal(param.kind, instance.values.get(param.name))
            if param.name in instance.values and literal is not None:
                fields.append(f"{param.ident}: Some({literal})")
        overrides = (nested or {}).get(element.name, [])
        binding = f"let {'mut ' if overrides else ''}args_{element.ident}"
        if fields:
            rest = ", ..Default::default()" if len(fields) < len(component.params) else ""
            lines.append(f"{binding} = {component.type_name}Params {{ {', '.join(fields)}{rest} }};")
        else:
            lines.append(f"{binding} = {component.type_name}Params::default();")
        lines += overrides
        lines += [
            f"let bin_{element.ident} = build_{component.ident}({key}, &args_{element.ident})?;",
            f"container.add(&bin_{element.ident})?;",
            f"elements.insert({key}.into(), bin_{element.ident}.upcast());",
        ]
    return lines


def _links(scope: ScopePlan) -> list[str]:
    """Links, then pad properties and pad-typed properties (they need the requested pads)."""
    lines = []
    for link in scope.spec.links:
        function = "link_dynamic" if link.edge.id in scope.dynamic_edges else "link"
        pads = (link.source.name, link.source_pad, link.target.name, link.target_pad)
        lines.append(f"rt::{function}(&elements, {', '.join(rust_str(p) for p in pads)})?;")
    for element in scope.spec.elements:
        if element.node.id in scope.instances:
            continue
        target = f"&elements[{rust_str(element.name)}]"
        for pad, specs in element.pad_properties:
            lines.append(f"rt::configure_pad({target}, {rust_str(pad)}, {_property_list(specs)})?;")
        for ref in element.pad_refs:
            lines.append(f"rt::apply_value({target}, {rust_str(ref.name)}, {rust_str(ref.text)}, None)?;")
    return lines


def _container(scope: ScopePlan, container: str) -> list[str]:
    if not scope.spec.elements:
        return ["let elements = Elements::new();"]
    return [f"let container = {container};", "let mut elements = Elements::new();"]


def _params_struct(plan: ComponentPlan) -> list[str]:
    fields = []
    for param in plan.params:
        default = typed_literal(param.kind, param.default) if param.default is not None else None
        doc = " ".join(
            x for x in (param.description.replace("\n", " "), f"(default: {default})" if default else "") if x
        )
        if doc:
            fields.append(f"    /// {doc}")
        fields.append(f"    pub {param.ident}: Option<{RS_TYPES[param.kind]}>,")
    return [
        "",
        f"/// Parameters of the {rust_str(plan.component.name)} component.",
        "/// `None` keeps the parameter default, or else the value of the inner element.",
        "#[derive(Clone, Debug, Default)]",
        f"pub struct {plan.type_name}Params {{",
        *fields,
        "}",
    ]


def _builder(plan: ComponentPlan) -> list[str]:
    scope = plan.scope
    instances = {i.node.name: i for i in scope.instances.values()}
    idents = {e.name: e.ident for e in scope.spec.elements}
    locals_, element_values, pad_values = [], [], []
    nested: dict[str, list[str]] = {}
    for param in plan.params:
        if not param.targets:
            continue
        default = typed_literal(param.kind, param.default) if param.default is not None else None
        fallback = f".or(Some({default}))" if default else ""
        locals_.append(f"let {param.ident} = params.{param.ident}.clone(){fallback};")
        for target in param.targets:
            if target.element in instances:
                inner = instances[target.element].component.params
                field = next((p.ident for p in inner if p.name == target.property), target.property)
                args = f"args_{idents[target.element]}"
                nested.setdefault(target.element, []).extend(
                    [f"if {param.ident}.is_some() {{", f"    {args}.{field} = {param.ident}.clone();", "}"]
                )
                continue
            pad = f"Some({rust_str(target.pad)})" if target.pad else "None"
            element = f"&elements[{rust_str(target.element)}]"
            apply = f"rt::apply_value({element}, {rust_str(target.property)}, &value.to_string(), {pad})?;"
            statement = [f"if let Some(value) = &{param.ident} {{", f"    {apply}", "}"]
            (pad_values if target.pad or target.pad_ref else element_values).extend(statement)
    ports = ", ".join(f"{p.name} ({p.direction})" for p in plan.ports) or "none"
    body = [
        *_container(scope, "gst::Bin::builder().name(name).build()"),
        *locals_,
        *_elements(scope, nested),
        *element_values,
        *_links(scope),
        *pad_values,
        *[
            f"rt::expose_port(&container, &elements[{rust_str(p.element)}], {rust_str(p.pad)}, "
            f"{rust_str(p.name)}, {rust_str(p.presence)})?;"
            for p in plan.ports
        ],
        "Ok(container)",
    ]
    if not scope.spec.elements:
        body.insert(0, "let container = gst::Bin::builder().name(name).build();")
    params_arg = f"{'params' if locals_ else '_params'}: &{plan.type_name}Params"
    return [
        "",
        f"/// {plan.component.name}: a bin named `name` with ghost pads {ports}.",
        f"pub fn build_{plan.ident}(name: &str, {params_arg}) -> Result<gst::Bin> {{",
        *[f"    {line}" for line in body],
        "}",
    ]


def _pipeline(program: ProgramPlan, cls: str) -> list[str]:
    body = [
        "gst::init()?;",
        f"let pipeline = gst::Pipeline::builder().name({rust_str(program.name)}).build();",
        *_container(program.root, "pipeline.clone().upcast::<gst::Bin>()"),
        *_elements(program.root),
        *_links(program.root),
        "let inner = Inner {",
        "    pipeline,",
        "    elements,",
        "    callbacks: Mutex::default(),",
        "    watch: Mutex::default(),",
        "    main_loop: Mutex::default(),",
        "    error: Mutex::default(),",
        "};",
        "Ok(Self { inner: Arc::new(inner) })",
    ]
    return [
        "",
        "// ---- Pipeline",
        PIPELINE.replace("PIPELINE", cls).replace("NAME", program.name).rstrip("\n"),
        "",
        f"impl {cls} {{",
        "    /// Creates the elements (and component bins), sets their properties and links them.",
        "    pub fn new() -> Result<Self> {",
        *[f"        {line}" for line in body],
        "    }",
        "}",
        "",
        "// ---- Demo (replace with your application)",
        "",
        "fn main() -> Result<()> {",
        f"    {cls}::new()?.run()",
        "}",
    ]


def render(
    graph: Graph, catalog: Catalog, name: str, components: Mapping[str, Component] | None = None
) -> str:
    library = components or {}
    program = build_program(graph, catalog, library, name, RUST_KEYWORDS)
    stem = camel_case(name)
    cls = stem if stem.endswith("Pipeline") else f"{stem}Pipeline"
    builders = "".join(
        f"//!   build_{c.ident}(name, &{c.type_name}Params {{ .. }}) -> gst::Bin  ({c.component.name})\n"
        for c in program.components
    )
    description = render_description(flatten(graph, library), catalog) or "(empty)"
    prelude = _PRELUDE.format(
        name=name,
        description=description.replace("\n", " "),
        cls=cls,
        builders=f"//!\n//! Components (reusable bins):\n{builders}" if builders else "",
    )
    code: list[str] = [RT.strip("\n")]
    if program.components:
        code += ["", "// ---- Components"]
    for component in program.components:
        code += _params_struct(component) + _builder(component)
    code += _pipeline(program, cls)
    return prelude + "\n" + "\n".join(code) + "\n"
