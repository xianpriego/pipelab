def _dicts(specs: tuple[PropertySpec, ...]) -> tuple[str, str]:
    typed = ", ".join(f"{p.name!r}: {p.value!r}" for p in specs if p.kind != "parse")
    parsed = ", ".join(f"{p.name!r}: {p.text!r}" for p in specs if p.kind == "parse")
    return f"{{{typed}}}", f"{{{parsed}}}"


class ScopeRenderer:
    """Lines building one graph scope into ``container`` with ``elements`` and ``host``."""

    def __init__(self, classes: dict[int, str], indent: str = "    ") -> None:
        self.classes = classes
        self.indent = indent

    def elements(self, scope: ScopePlan, nested_args: dict[str, list[str]] | None = None) -> list[str]:
        lines = []
        for element in scope.spec.elements:
            instance = scope.instances.get(element.node.id)
            if instance is None:
                typed, parsed = _dicts(element.properties)
                lines.append(
                    f"elements[{element.name!r}] = make_element(container, {element.factory!r}, "
                    f"{element.name!r}, {typed}, {parsed})"
                )
                continue
            values = {
                p.ident: instance.values[p.name]
                for p in instance.component.params
                if p.name in instance.values
            }
            args = f"args_{element.ident}"
            lines.append(f"{args} = {values!r}")
            lines += (nested_args or {}).get(element.name, [])
            lines.append(
                f"elements[{element.name!r}] = "
                f"build_{instance.component.ident}({element.name!r}, host, **{args})"
            )
            lines.append(f"container.add(elements[{element.name!r}])")
        return lines

    def links(self, scope: ScopePlan) -> list[str]:
        lines = []
        for link in scope.spec.links:
            function = "link_dynamic" if link.edge.id in scope.dynamic_edges else "link"
            args = (link.source.name, link.source_pad, link.target.name, link.target_pad)
            lines.append(f"{function}(elements, {', '.join(literal(a) for a in args)})")
        for element in scope.spec.elements:
            if element.node.id in scope.instances:
                continue
            for pad, specs in element.pad_properties:
                typed, parsed = _dicts(specs)
                lines.append(f"configure(pad_of(elements[{element.name!r}], {pad!r})[0], {typed}, {parsed})")
            for ref in element.pad_refs:
                lines.append(f"apply_value(elements[{element.name!r}], {ref.name!r}, {str(ref.value)!r})")
        return lines

    def probes(self, scope: ScopePlan, graph: Graph, instance: str) -> list[str]:
        lines = []
        for rule_set in scope.probes:
            target = rule_set.target
            if target.kind == "edge":
                edge = graph.edge(target.id)
                if edge is None:
                    continue
                node, pad = graph.node(edge.source), edge.source_pad
            else:
                node, pad = graph.node(target.id), target.pad
            if node is None:
                continue
            probe_id = f"f'{{name}}/{rule_set.id}'" if instance else repr(rule_set.id)
            lines.append(
                f"{self.classes[id(rule_set)]}(host, elements, {node.name!r}, {pad!r}, {target.kind!r}, "
                f"{probe_id}, {instance or repr('')}, {node.name!r}).attach()"
            )
        return lines


@dataclass
class _ParamLines:
    defaults: list[str] = field(default_factory=list)  # resolve definition defaults
    elements: list[str] = field(default_factory=list)  # inner element properties (before linking)
    pads: list[str] = field(default_factory=list)  # pad properties / pad references (after linking)
    nested: dict[str, list[str]] = field(default_factory=dict)  # kwargs of nested instances


def _param_lines(plan: ComponentPlan) -> _ParamLines:
    result = _ParamLines()
    scope = plan.scope
    instance_names = {i.node.name for i in scope.instances.values()}
    for param in plan.params:
        if param.default is not None:
            result.defaults.append(
                f"{param.ident} = {param.default!r} if {param.ident} is None else {param.ident}"
            )
        for target in param.targets:
            if target.element in instance_names:
                key = f"args_{_ident_of(scope, target.element)}"
                nested_param = _nested_ident(scope, target.element, target.property)
                result.nested.setdefault(target.element, []).extend(
                    [f"if {param.ident} is not None:", f"    {key}[{nested_param!r}] = {param.ident}"]
                )
                continue
            element = f"elements[{target.element!r}]"
            statement = f"apply_value({element}, {target.property!r}, {param.ident}, {target.pad!r})"
            lines = [f"if {param.ident} is not None:", f"    {statement}"]
            (result.pads if target.pad or target.pad_ref else result.elements).extend(lines)
    return result


def _ident_of(scope: ScopePlan, name: str) -> str:
    return next(e.ident for e in scope.spec.elements if e.name == name)


def _nested_ident(scope: ScopePlan, name: str, param: str) -> str:
    instance = next(i for i in scope.instances.values() if i.node.name == name)
    return next((p.ident for p in instance.component.params if p.name == param), param)


def render_component(plan: ComponentPlan, renderer: ScopeRenderer) -> list[str]:
    scope = plan.scope
    keywords = "".join(f", {p.ident}: {_PY_TYPES[p.kind]} | None = None" for p in plan.params)
    star = ", *" if plan.params else ""
    signature = (
        f"def build_{plan.ident}(name: str, host: ProbeHost | None = None{star}{keywords}) -> Gst.Bin:"
    )
    ports = ", ".join(f"{p.name} ({p.direction})" for p in plan.ports) or "none"
    params = _param_lines(plan)
    body = [
        f'"""{plan.component.name}. Ports: {ports}.',
        "",
        "Its probe rule sets run once ``host.start()`` is called (the pipeline does it on PLAYING).",
        '"""',
        "host = host if host is not None else ProbeHost()",
        "container = Gst.Bin.new(name)",
        "elements = {}",
        *params.defaults,
        *renderer.elements(scope, params.nested),
        *params.elements,
        *renderer.links(scope),
        *params.pads,
        *[
            f"expose_port(container, elements[{p.element!r}], {p.pad!r}, {p.name!r}, {p.presence!r})"
            for p in plan.ports
        ],
        *renderer.probes(scope, plan.component.graph, "name"),
        "return container",
    ]
    return ["", "", signature, *[f"    {line}".rstrip() for line in body]]


def render(
    graph: Graph, catalog: Catalog, name: str, components: Mapping[str, Component] | None = None
) -> str:
    program = build_program(graph, catalog, components or {}, name)
    slots = {s.slot.id: s.slot.id for s in program.slots} | {s.slot.name: s.slot.id for s in program.slots}
    functions = {f.function.name: f.ident for f in program.functions}
    classes: dict[int, str] = {}
    rule_sets = []
    for owner, scope in [(c.component.id, c.scope) for c in program.components] + [(name, program.root)]:
        for rule_set in scope.probes:
            cls = class_name(rule_set, owner)
            classes[id(rule_set)] = cls
            rule_sets += render_rule_set(rule_set, cls, slots, functions)
    renderer = ScopeRenderer(classes)
    scripts = HARNESS + scripts_table(graph) if enabled_scripts(graph) else ""
    support = SUPPORT + RULES + SLOTS
    lines = [_prelude(program), support.rstrip("\n"), scripts.rstrip("\n"), *rule_sets]
    for component in program.components:
        lines += render_component(component, renderer)
    lines += render_pipeline_class(program, graph, renderer, bool(scripts))
    return "\n".join(line for line in lines if line is not None) + "\n"


def _prelude(program: ProgramPlan) -> str:
    api = []
    for slot in program.slots:
        api.append(f"    pipeline.add_{slot.item}(...) / remove_{slot.item}(id) / list_{slot.ident}()")
    for function in program.functions:
        api.append(f"    pipeline.{function.ident}(...)")
    text = "\n".join(api)
    return _PRELUDE.format(
        name=program.name, cls=f"{program.type_name}Pipeline", api=text + "\n" if text else ""
    )
